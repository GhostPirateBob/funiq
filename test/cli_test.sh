#!/usr/bin/env bash
# CLI-level regression tests: behaviour that only shows up when running the
# real binary (exit codes, raw stdout bytes, argument defaults, tty paths).
# Usage: test/cli_test.sh path/to/funiq
set -u
# Colour is decided from these; the caller's environment must not leak in.
unset FORCE_COLOR NO_COLOR

FUNIQ=${1:?usage: $0 path/to/funiq}
# Terminal tests use util-linux script(1) to give funiq a tty. BSD script
# (macOS) takes different arguments, and Windows has none: skip there.
UTIL_LINUX_SCRIPT=0
if [ "${OS:-}" != "Windows_NT" ] && script -V 2>&1 | grep -q util-linux; then UTIL_LINUX_SCRIPT=1; fi
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

pass=0
fail=0
skip=0
ok() { pass=$((pass + 1)); echo "PASS  $1"; }
ko() { fail=$((fail + 1)); echo "FAIL  $1"; [ -n "${2:-}" ] && echo "      $2"; }
sk() { skip=$((skip + 1)); echo "SKIP  $1 ($2)"; }

SHIPS="$TMP/ships.txt"
printf '%s\n' 'USS Enterprise' 'uss enterprize' 'U.S.S. Enterprise' 'Enterprize' \
	'USS Voyager' 'USS Voyagr' 'uss-voyager' 'USS Defiant' 'USS Defient' 'Defiant' > "$SHIPS"

# --- missing input file is an error, not silent empty output ---------------
name="missing file exits non-zero with a message"
err=$("$FUNIQ" "$TMP/does-not-exist.txt" 2>&1 >/dev/null)
rc=$?
if [ $rc -ne 0 ] && printf '%s' "$err" | grep -q 'does-not-exist.txt'; then
	ok "$name"
else
	ko "$name" "rc=$rc stderr='$err'"
fi

# --- stdout uses LF line endings on every platform --------------------------
name="output has no CR bytes"
if printf 'alpha\nzzzzzzzz\n' | "$FUNIQ" | od -c | grep -q '\\r'; then
	ko "$name" "found \\r in output"
else
	ok "$name"
fi

# --- normalized method gets a sane default threshold ------------------------
# Without -d, the old default of 3 made every normalized comparison match.
name="-m normalized-levenshtein without -d does not collapse distinct lines"
n=$(printf '%s\n' cat elephant monkey xyzzy | "$FUNIQ" -m normalized-levenshtein | wc -l)
if [ "$n" -eq 4 ]; then ok "$name"; else ko "$name" "got $n lines, want 4"; fi

# --- README examples stay true ----------------------------------------------
name="README -iI example (Enterprize stays apart at the default threshold)"
want=$(printf '%s\n' 'Enterprize' 'USS Defiant' 'USS Enterprise' 'USS Voyager')
got=$("$FUNIQ" -iI "$SHIPS")
if [ "$got" = "$want" ]; then ok "$name"; else ko "$name" "got: $got"; fi

name="README -c example"
want=$(printf '%s\n' '      3 USS Defiant' '      4 USS Enterprise' '      3 USS Voyager')
got=$("$FUNIQ" -iI -d 4 -c "$SHIPS")
if [ "$got" = "$want" ]; then ok "$name"; else ko "$name" "got: $got"; fi

name="README --scores example"
want=$(printf '%s\t%s\t%s\n%s\t%s\t%s\t%s\n%s\t%s\t%s\n' \
	'USS Defiant' 'USS Defient (1)' 'Defiant (3)' \
	'USS Enterprise' 'uss enterprize (1)' 'U.S.S. Enterprise (0)' 'Enterprize (4)' \
	'USS Voyager' 'USS Voyagr (1)' 'uss-voyager (0)')
got=$("$FUNIQ" -iI -d 4 --scores "$SHIPS")
if [ "$got" = "$want" ]; then ok "$name"; else ko "$name" "got: $(printf '%s' "$got" | od -c | head -3)"; fi

# --- golden outputs: matching results must not drift ------------------------
# Generated by the pre-optimisation binary; any speedup must reproduce them
# byte-for-byte. Fixture is synthetic (TEST-NET IPs, example.com only).
FIX="$(dirname "$0")/fixtures"
golden() {
	local gold=$1; shift
	if "$FUNIQ" "$@" "$FIX/synthetic.log" | cmp -s - "$FIX/$gold"; then
		ok "golden $gold"
	else
		ko "golden $gold" "output differs from $FIX/$gold"
	fi
}
golden golden-default.txt
golden golden-default-preset-counts.txt --default -c
golden golden-iI-d3-all.txt -iI -d 3 -a
golden golden-norm-0.3-counts.txt -c -m normalized-levenshtein -d 0.3
golden golden-d40-counts.txt -d 40 -c
golden golden-norm-1-counts.txt -m normalized-levenshtein -d 1 -c
golden golden-iI-norm-0.05-all.txt -iI -m normalized-levenshtein -d 0.05 -a
# Bare -d (not followed by a number) is the --default preset
golden golden-default-preset-counts.txt -d -c
golden golden-default-preset-counts.txt -c -d
golden golden-default-preset-counts.txt -c -j 2 -d
# Thread count must never change results
golden golden-default-preset-counts.txt --default -c -j 1
golden golden-default-preset-counts.txt --default -c -j 8
golden golden-iI-d3-all.txt -iI -d 3 -a --threads 3
golden golden-norm-0.3-counts.txt -c -m normalized-levenshtein -d 0.3 -j 16

# --- v1 flags ----------------------------------------------------------------
expect() { # name, expected output, funiq args... (stdin from $IN)
	local name=$1 want=$2; shift 2
	local got
	got=$(printf '%b' "$IN" | "$FUNIQ" "$@" 2>&1)
	if [ "$got" = "$want" ]; then ok "$name"; else ko "$name" "got: $(printf '%s' "$got" | head -3)"; fi
}
IN='pid 123 exited\npid 98765 exited\npid exited\n'
expect "--mask-digits groups lines differing only in numbers" \
	"$(printf '%s\n' '      2 pid 123 exited' '      1 pid exited')" --mask-digits -d 0 -c
IN='connection reset by peer\npeer by reset connection\n'
expect "-m token-sort ignores word order (default threshold)" "      2 connection reset by peer" -m token-sort -c
IN='user=alice action=login status=ok\nstatus=ok action=login user=alice\n'
expect "-m cosine matches reordered fields" "      2 user=alice action=login status=ok" -m cosine -d 0.2 -c
IN='abc\nabcdef\n'
expect "--rep longest prints the longest member" "      2 abcdef" --rep longest -c
IN='hello\nhallo\n'
expect "--scores prints distances" "$(printf 'hello\thallo (1)')" --scores -d 2
IN='aaaaaa\naaabbb\naaaabb\n'
expect "--best joins the closest group" "$(printf '%s\n' '      1 aaaaaa' '      2 aaabbb')" --best -d 2 -c
IN='hello\nhallo\nhelp!\n'
expect "README --scores example" "$(printf 'hello\thallo (1)\thelp! (2)')" -d 2 --scores

name="README usage block matches funiq -h"
README="$(dirname "$0")/../README.md"
want=$(sed -n '/<!-- usage:start/,/<!-- usage:end -->/p' "$README" | sed '1,2d;$d' | sed '$d')
got=$("$FUNIQ" -h)
if [ "$got" = "$want" ]; then ok "$name"; else ko "$name" "regenerate the README block from: funiq -h"; fi

[ "$(printf 'x\n' | "$FUNIQ" --rep sideways >/dev/null 2>&1; echo $?)" != 0 ] && ok "--rep sideways exits non-zero" || ko "--rep sideways exits non-zero"

# --- non-seekable file argument with progress bar active --------------------
# Progress (stderr is a tty) pre-counts lines then rewinds; a FIFO can't rewind.
name="FIFO filename with tty stderr keeps all lines"
if [ "$UTIL_LINUX_SCRIPT" != 1 ]; then
	sk "$name" "needs util-linux script(1)"
else
	seq 1 120 | sed 's/^/line unique-/' | awk '{print $0 "-" NR*7919}' > "$TMP/in.txt"
	n=$(script -qec "'$FUNIQ' -d 0 <(cat '$TMP/in.txt') 2>/dev/tty | wc -l" /dev/null | tr -d '\r' | tail -1)
	if [ "$n" = "120" ]; then ok "$name"; else ko "$name" "got '$n' lines, want 120"; fi
fi

# --- colour ------------------------------------------------------------------
ESC=$(printf '\033')
strip() { sed "s/${ESC}\[[0-9;]*m//g"; }
has_esc() { grep -q "$ESC"; }
printf 'aaaa\naaab\nzzzz\n' > "$TMP/col.txt"
plain=$("$FUNIQ" -c --scores -d 1 "$TMP/col.txt")

name="piped output has no colour by default"
if "$FUNIQ" -c --scores -d 1 "$TMP/col.txt" | has_esc; then ko "$name"; else ok "$name"; fi

for form in "--color=always" "--color always"; do
	name="$form colours output; stripped it equals the plain output"
	out=$("$FUNIQ" $form -c --scores -d 1 "$TMP/col.txt")
	if printf '%s' "$out" | has_esc && [ "$(printf '%s' "$out" | strip)" = "$plain" ]; then ok "$name"; else ko "$name"; fi
done

name="FORCE_COLOR=1 colours piped output"
FORCE_COLOR=1 "$FUNIQ" -c "$TMP/col.txt" | has_esc && ok "$name" || ko "$name"
name="--color=never beats FORCE_COLOR=1"
FORCE_COLOR=1 "$FUNIQ" --color=never -c "$TMP/col.txt" | has_esc && ko "$name" || ok "$name"
name="FORCE_COLOR=1 beats NO_COLOR=1"
FORCE_COLOR=1 NO_COLOR=1 "$FUNIQ" -c "$TMP/col.txt" | has_esc && ok "$name" || ko "$name"
name="FORCE_COLOR=0 keeps output plain"
FORCE_COLOR=0 "$FUNIQ" -c "$TMP/col.txt" | has_esc && ko "$name" || ok "$name"
name="--color rejects unknown values"
"$FUNIQ" --color=sometimes "$TMP/col.txt" >/dev/null 2>&1 && ko "$name" || ok "$name"

name="errors on stderr are coloured with --color=always, plain otherwise"
e1=$("$FUNIQ" --color=always "$TMP/nope.txt" 2>&1 >/dev/null)
e2=$("$FUNIQ" "$TMP/nope.txt" 2>&1 >/dev/null)
if printf '%s' "$e1" | has_esc && ! printf '%s' "$e2" | has_esc \
	&& [ "$(printf '%s' "$e1" | strip)" = "$e2" ]; then ok "$name"; else ko "$name" "e1=$e1 e2=$e2"; fi

name="bare -d as the last argument reads stdin with the preset"
[ "$(printf 'Hello, World\nhello world!\n' | "$FUNIQ" -c -d)" = "      2 Hello, World" ] && ok "$name" || ko "$name"
name="-d <number> still sets the distance (lserrors-style call)"
[ "$(printf 'abcdefgh\nabcdefgX\n' | "$FUNIQ" -iI -m normalized-levenshtein -d 0.1 -c | wc -l)" -eq 2 ] && ok "$name" || ko "$name"

name="--long=value works for any option (--rep=longest)"
[ "$(printf 'abc\nabcdef\n' | "$FUNIQ" --rep=longest -c)" = "      2 abcdef" ] && ok "$name" || ko "$name"

name="a terminal gets colour by default, NO_COLOR=1 turns it off"
if [ "$UTIL_LINUX_SCRIPT" != 1 ]; then
	sk "$name" "needs util-linux script(1)"
else
	t1=$(script -qec "'$FUNIQ' -c '$TMP/col.txt'" /dev/null)
	t2=$(NO_COLOR=1 script -qec "'$FUNIQ' -c '$TMP/col.txt'" /dev/null)
	if printf '%s' "$t1" | has_esc && ! printf '%s' "$t2" | has_esc; then ok "$name"; else ko "$name"; fi

	# The progress bar is for big inputs (50+ lines); its final newline is too,
	# so drawing it for a few lines left a dangling bar before the results.
	name="no progress bar for small inputs on a terminal"
	t3=$(script -qec "'$FUNIQ' -c '$TMP/col.txt'" /dev/null)
	if printf '%s' "$t3" | grep -q Processing; then ko "$name"; else ok "$name"; fi
fi

echo "cli: $pass passed, $fail failed, $skip skipped"
[ $fail -eq 0 ]
